BLUE, ORANGE, GRAY, GREEN = '#0072B2', '#D55E00', '#6B7280', '#009E73'

def save(fig, name):
    for ext in ('png','svg','pdf'):
        fig.savefig(OUT/f'{name}.{ext}', dpi=220, bbox_inches='tight', facecolor='white')
    plt.close(fig)

def box(ax, xy, w, h, text, fill='#F2F5F7'):
    patch=FancyBboxPatch(xy,w,h,boxstyle='round,pad=0.012,rounding_size=0.012',
                       linewidth=.9,edgecolor='#64748B',facecolor=fill)
    ax.add_patch(patch)
    ax.text(xy[0]+w/2,xy[1]+h/2,text,ha='center',va='center',fontsize=10.5,linespacing=1.35)

def arrow(ax, a, b):
    ax.add_patch(FancyArrowPatch(a,b,arrowstyle='-|>',mutation_scale=11,
                               linewidth=1,color='#475569'))

